/**
 * The coverage numbers, computed from the data files rather than typed by hand.
 *
 * Every doc that used to carry its own copy of these numbers drifted (four
 * different answers in four auto-loaded files on 2026-09-23). The numbers now
 * live in one generated block at the top of docs/status.md, between the
 * markers below; everything else points there.
 *
 * Inputs: data/required-symbols.json, data/arch-inventory.json (A1 classes, optional), data/dropped.json (A2), data/merged-<v>.json (run
 * tools/merge-symbols.mjs first -- this reads its output, it does not merge),
 * data/derived.json.
 *
 * Usage:
 *   node tools/status-summary.mjs            print the block
 *   node tools/status-summary.mjs --write    replace the block in docs/status.md
 *   node tools/status-summary.mjs --check    exit 1 if docs/status.md is stale
 */
import * as fs from "fs";

const BUILDS = ["1.26.40.8", "1.26.51.1"];
const STATUS = "docs/status.md";
const BEGIN = "<!-- status-summary:begin (generated by tools/status-summary.mjs -- do not edit by hand) -->";
const END = "<!-- status-summary:end -->";

const load = f => JSON.parse(fs.readFileSync(f, "utf8"));
const req = load("data/required-symbols.json").symbols.map(s => s.name);
const derivedFile = load("data/derived.json");
const derived = derivedFile.derived;

const rows = BUILDS.map(v => {
    const m = load(`data/merged-${v}.json`);
    const has = (o, n) => o != null && n in o;
    const byAddress = req.filter(n => has(m.symbols, n)).length;
    const emitted = req.filter(n => !has(m.symbols, n) && (has(m.accessors, n) || has(m.constants, n))).length;
    // a derived() name the table also resolves is served from the binary (derived() in bds/symbols.ts),
    // so it counts once
    const bdsx = req.filter(n => has(derived, n) && !has(m.symbols, n) && !has(m.accessors, n) && !has(m.constants, n)).length;
    return { v, names: Object.keys(m.symbols).length, byAddress, emitted, bdsx, resolvable: byAddress + emitted + bdsx };
});

const pair = k => rows.map(r => r[k]).join(" / ");

// A1's classes (tools/arch-inventory.mjs), when the inventory has been generated
const INV = "data/arch-inventory.json";
const inv = fs.existsSync(INV) ? load(INV) : null;
const invLine = inv
    ? `Classes (\`${INV}\`, ${inv.generatedAt}; missing on either build, plus every derived entry): ` +
      ["live", "moved", "absorbed", "gone", "unknown"].map(c => (c === "unknown" ? `**unknown ${inv.counts[c]}** (${inv.counts.unknownNotGone ?? 0} of them shown not gone)` : `${c} ${inv.counts[c]}`)).join(", ") +
      (inv.notRequired ? `; plus ${Object.keys(inv.notRequired).length} verdicts on names outside the required set (${Object.values(inv.notRequired).filter(v => v.class === "gone").length} gone, A2's input)` : "") + "."
    : `Classes: \`${INV}\` not generated (\`node tools/arch-inventory.mjs\`).`;
// A2: names whose API was removed from bdsx because the concept is gone (data/dropped.json)
const dropped = fs.existsSync("data/dropped.json") ? Object.keys(load("data/dropped.json").dropped).length : 0;
const block = [
    BEGIN,
    `Coverage of bdsx's **${req.length}** required names (${BUILDS.join(" / ")})` +
        (dropped ? `; **${dropped}** names dropped from bdsx as gone in 1.26 (\`data/dropped.json\`):` : ":"),
    "",
    "| | " + BUILDS.join(" | ") + " |",
    "|---|" + BUILDS.map(() => "---:").join("|") + "|",
    `| by address (\`symbols\`) | ${rows.map(r => r.byAddress).join(" | ")} |`,
    `| + offsets and values (\`accessors\`, \`constants\`) | ${rows.map(r => r.byAddress + r.emitted).join(" | ")} |`,
    `| + implemented by bdsx (\`data/derived.json\`, not also in the table) | **${rows.map(r => r.resolvable).join("** | **")}** |`,
    `| names in the merged table, required or not | ${rows.map(r => r.names.toLocaleString("en-US")).join(" | ")} |`,
    "",
    `\`data/derived.json\` has ${Object.keys(derived).length} entries (generated ${derivedFile.generatedAt ?? "?"}).`,
    `In short: **${pair("byAddress")} by address, ${pair("resolvable")} resolvable.**`,
    invLine,
    "Regenerate after every merge: `node tools/status-summary.mjs --write`.",
    END,
].join("\n");

const args = process.argv.slice(2);
if (args.includes("--write") || args.includes("--check")) {
    // compared with LF line ends whatever the checkout did (git on Windows may write CRLF)
    const text = fs.readFileSync(STATUS, "utf8").replace(/\r\n/g, "\n");
    const a = text.indexOf(BEGIN), b = text.indexOf(END);
    if (a < 0 || b < a) { console.error(`${STATUS}: markers not found`); process.exit(2); }
    const next = text.slice(0, a) + block + text.slice(b + END.length);
    if (args.includes("--check")) {
        if (next !== text) { console.error(`${STATUS}: summary is stale -- run node tools/status-summary.mjs --write`); process.exit(1); }
        console.log(`${STATUS}: summary is current`);
    } else {
        fs.writeFileSync(STATUS, next);
        console.log(`${STATUS}: summary ${next === text ? "unchanged" : "updated"}`);
    }
} else {
    console.log(block);
}
